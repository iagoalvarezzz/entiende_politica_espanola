    for (id_, bloque, tipo, enunciado, opciones, correcta, explicacion, fuente, articulo, etiqueta) in P + P_H4:
        r = {
            "id": id_,
            "modulo": bloque.split("-")[0],
            "bloque": bloque,
            "tipo": tipo,
            "enunciado": enunciado,
        }
        if opciones:
            r["opciones"] = [{"id": i, "texto": t} for i, t in opciones]
        r["correcta"] = correcta
        if tipo == "numerica":
            r["tolerancia"] = 0
